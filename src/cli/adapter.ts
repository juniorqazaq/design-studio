import { readFile, writeFile, rename, unlink, mkdir, lstat } from 'node:fs/promises';
import { dirname, extname, relative } from 'node:path';
import { randomUUID } from 'node:crypto';
import postcss from 'postcss';
import { declarations, toCSS, scaleCSS, migrationCSS, validateConfig, themes, themeSelector, type DesignConfig } from '../shared/design.js';
import {unconditional} from '../shared/project-colors.js';
import { safePath, readLimited, isManagedStylesheet } from './project.js';
export interface Change { path: string; before: string | null; after: string; }
export async function planApply(root: string,c: DesignConfig,target?:string): Promise<Change> {
  const path=await safePath(root,target??[c.application.directory,'design.tokens.css'].filter(Boolean).join('/'));
  if (extname(path)!=='.css') throw new Error('The supported adapter requires a .css file.');
  let before:string|null=null;
  try { before=await readLimited(path); } catch (e) { if ((e as NodeJS.ErrnoException).code!=='ENOENT') throw e; }
  const unmanaged='design.tokens.css exists and is not managed by Design Studio. Choose an explicit --target or move it yourself.';
  if(!target&&before!==null&&!/\/\* Generated by (Design Studio|Token Studio)\./.test(before))throw new Error(unmanaged);
  const ast=before===null?null:postcss.parse(before,{from:path}),managed=ast!==null&&isManagedStylesheet(ast);
  if (!target) {
    if (before!==null && !managed) throw new Error(unmanaged);
    if (before===null) return {path,before,after:toCSS(c)};
  }
  if (ast===null) throw new Error('--target must name an existing CSS token file. Omit --target to introduce a token layer.');
  const names=new Set(Object.keys(declarations(c,'light')));
  // A separate layer must outrank equally scoped project tokens, regardless of Vite import order.
  const layer=!target||managed;
  if(layer) ast.walkRules(rule=>{for(const theme of themes)if(rule.selector===themeSelector(c,theme)||rule.selector===themeSelector({...c,application:{scope:c.application.scope}},theme,true))rule.selector=themeSelector(c,theme,true);});
  const selectors=themes.map(t=>themeSelector(c,t,layer));
  let matched=false;
  ast.walkDecls(d=>{
    if (!names.has(d.prop)) return;
    if (d.parent?.type!=='rule' || !unconditional(d.parent) || !selectors.includes(d.parent.selector)) throw new Error(`${d.prop} appears in an unsupported selector or conditional. Use a separate token layer or simplify the token file.`);
    if (d.important) throw new Error(`${d.prop} uses !important. Remove it explicitly before applying.`);
    matched=true;
  });
  if (!matched) throw new Error('No mapped variables found in the target. Edit tokenMappings or omit --target to introduce a token layer.');
  for (const theme of themes) {
    const selector=themeSelector(c,theme,layer), rules:postcss.Rule[]=[];ast.walkRules(rule=>{if(rule.selector===selector&&unconditional(rule))rules.push(rule);});
    if (rules.length>1) throw new Error(`Multiple ${selector} blocks found. Consolidate them before applying.`);
    const rule=rules[0] as postcss.Rule|undefined ?? postcss.rule({selector});
    if (!rules.length) ast.append(rule);
    for (const [prop,value] of Object.entries(declarations(c,theme))) {
      const found=rule.nodes.filter(n=>n.type==='decl' && n.prop===prop) as postcss.Declaration[];
      if (found.length>1) throw new Error(`Duplicate ${prop} in ${selector}. Consolidate it before applying.`);
      if (found.length) found[0].value=value; else rule.append({prop,value});
    }
  }
  const starts:postcss.Comment[]=[],ends:postcss.Comment[]=[];
  ast.walkComments(comment=>{if(comment.text==='Design Studio typography scale')starts.push(comment);if(comment.text==='End Design Studio typography scale')ends.push(comment);});
  if(c.application.applyTypography!==false&&(starts.length||ends.length)){
    if(starts.length!==1||ends.length!==1||starts[0].parent!==ast||ends[0].parent!==ast)throw new Error('Ambiguous managed typography scale block. Review it manually before applying.');
    const begin=ast.nodes.indexOf(starts[0]),end=ast.nodes.indexOf(ends[0]),rules=ast.nodes.slice(begin+1,end);
    if(end<=begin||rules.length!==6||rules.some((node,i)=>node.type!=='rule'||![`h${i+1}`,`:root h${i+1}`,`.design-scope h${i+1}`].includes(node.selector)||node.nodes.length!==1||node.nodes[0].type!=='decl'||node.nodes[0].prop!=='font-size'||node.nodes[0].value!==`var(--ds-size-h${i+1})`||node.nodes[0].important))throw new Error('Managed typography scale block has custom edits. Preserve those edits by reviewing the block manually.');
    for(const node of ast.nodes.slice(begin,end+1))node.remove();
  }
  if(c.application.applyTypography!==false&&c.typography.scale!==undefined)ast.append(postcss.parse('\n\n'+scaleCSS(c)));
  const migrationStart=ast.nodes.filter(n=>n.type==='comment'&&n.text==='Design Studio color migrations'),migrationEnd=ast.nodes.filter(n=>n.type==='comment'&&n.text==='End Design Studio color migrations');
  let previous:DesignConfig|undefined;
  if(managed)try{previous=validateConfig(JSON.parse(await readLimited(await safePath(root,[c.application.directory,'design-studio-assets','design.config.json'].filter(Boolean).join('/')))));}catch(error){if((error as NodeJS.ErrnoException).code!=='ENOENT')throw error;}
  if(migrationStart.length||migrationEnd.length){
    if(!managed||!previous||migrationStart.length!==1||migrationEnd.length!==1)throw new Error('Ambiguous managed color migrations or missing saved configuration. Review them manually.');
    const begin=ast.nodes.indexOf(migrationStart[0]),end=ast.nodes.indexOf(migrationEnd[0]);
    const expected=[false,true].map(legacy=>postcss.parse(migrationCSS(previous,legacy)).nodes.map(n=>n.toString()).join('\n'));
    if(end<=begin||!expected.includes(ast.nodes.slice(begin,end+1).map(n=>n.toString()).join('\n')))throw new Error('Managed color migrations have custom edits. Preserve them before applying.');
    for(const node of ast.nodes.slice(begin,end+1))node.remove();
  }else if(previous?.application.migrations?.length){
    // Older versions emitted unmarked migration rules; replace only their exact generated content.
    const variants=[false,true].map(legacy=>postcss.parse(migrationCSS(previous!,legacy)).nodes.filter(n=>n.type==='rule'));
    const rules=variants.find(rules=>rules.every(rule=>{const matches=ast.nodes.filter(n=>n.type==='rule'&&n.selector===(rule as postcss.Rule).selector);return matches.length===1&&matches[0].toString()===rule.toString();}));
    if(!rules)throw new Error('Legacy color migrations have custom edits. Review them manually.');
    for(const rule of rules)ast.nodes.find(n=>n.type==='rule'&&n.selector===(rule as postcss.Rule).selector)!.remove();
  }
  if(managed&&c.application.migrations?.length)ast.append(postcss.parse('\n\n'+migrationCSS(c)));
  return {path,before,after:ast.toString()};
}
export function review(change: Change, root: string) {
  if (change.before===change.after) return `No changes: ${relative(root,change.path)}`;
  return `--- ${relative(root,change.path)} (before)\n+++ ${relative(root,change.path)} (proposed)\n`+(change.before??'').split('\n').map(l=>'- '+l).join('\n')+'\n'+change.after.split('\n').map(l=>'+ '+l).join('\n');
}
export async function writeChange(root:string,change:Change) {
  await safePath(root,change.path);
  let current:string|null=null;
  try { current=await readLimited(change.path); } catch(e) { if ((e as NodeJS.ErrnoException).code!=='ENOENT') throw e; }
  if (current!==change.before) throw new Error('Target changed since review. Run apply again to review its current state.');
  if (current===change.after) return;
  const temp=change.path+'.'+randomUUID()+'.tmp';
  const mode=current===null?0o644:(await lstat(change.path)).mode;
  try { await writeFile(temp,change.after,{flag:'wx',mode}); await rename(temp,change.path); }
  finally { await unlink(temp).catch(e=>{if(e.code!=='ENOENT')throw e;}); }
}
export async function exportSkill(root:string,name:string,files:Record<string,string|Uint8Array>) {
  const path=await safePath(root,name);
  // A new directory prevents silently overwriting a skill or user edits.
  await mkdir(path,{recursive:false});
  for (const [name,contents] of Object.entries(files)){const output=await safePath(path,name);await mkdir(dirname(output),{recursive:true});await writeFile(output,contents,{flag:'wx'});}
  return path;
}
