const ignored = new Set(['node_modules','dist','build','coverage','vendor','.next']);
export async function safePath(root: string, name: string) {
  const base=await realpath(root), target=resolve(base,name), rel=relative(base,target);
  if (!rel || rel.startsWith('..'+sep) || rel==='..' || rel.split(sep).some(part=>part.startsWith('.') || ignored.has(part))) throw new Error('Target must be a regular file or folder inside the project, outside hidden/build directories.');
  let current=base;
  for (const part of rel.split(sep)) {
    current=resolve(current,part);
    try { if ((await lstat(current)).isSymbolicLink()) throw new Error('Symlink targets are unsupported. Choose a regular project path.'); }
    catch (error) { if ((error as NodeJS.ErrnoException).code!=='ENOENT') throw error; }
  }
  return target;
}
export async function readLimited(path: string) {
  const stat=await lstat(path);
  if (!stat.isFile() || stat.isSymbolicLink() || stat.size>1_000_000) throw new Error('Expected a regular file smaller than 1 MB.');
  return readFile(path,'utf8');
}
export function isManagedStylesheet(sheet:postcss.Root){return sheet.nodes.some(node=>node.type==='comment'&&/^Generated by (Design Studio|Token Studio)\./.test(node.text));}
export interface Inspection { projectPath?:string; preview?:{url?:string;reason:string}; name: string; framework: string; styling: string[]; components: string[]; cssFiles: string[]; detected: { file: string; variable: string; value: string; hex?:string; format?:TokenFormat; selector?:string; theme: string; supported: boolean; priority: number }[]; hardcoded?:{file:string;selector:string;property:string;value:string}[]; scripts?:Record<string,string>; config: DesignConfig; notes: string[]; }
export async function inspectProject(root: string, directory=''): Promise<Inspection> {
  const report: Inspection={name:root.split(sep).pop()||'Project',framework:'Unknown',styling:[],components:[],cssFiles:[],detected:[],hardcoded:[],config:structuredClone(defaultConfig),notes:[]};
  try {
    const p=JSON.parse(await readLimited(await safePath(root,'package.json')));
    report.name=typeof p.name==='string'?p.name:report.name;
    report.scripts=p.scripts??{};
    const deps={...p.dependencies,...p.devDependencies};
    report.framework=deps.next?'Next.js':deps.react?'React':deps.vue?'Vue':deps.svelte?'Svelte':'Unknown';
    if (deps.tailwindcss) report.styling.push('Tailwind (inspection only)');
    if (deps['styled-components']) report.styling.push('styled-components (inspection only)');
  } catch (e) { report.notes.push(`Package metadata: ${(e as Error).message}`); }
  try{report.config=validateConfig(JSON.parse(await readLimited(await safePath(root,[directory,'design-studio-assets','design.config.json'].filter(Boolean).join('/')))));}catch(e){if((e as NodeJS.ErrnoException).code!=='ENOENT')report.notes.push(`Managed design configuration unavailable: ${(e as Error).message}`);}
  let count=0, exhausted=false;
  async function walk(dir: string, depth: number) {
    if (depth>6) { exhausted=true;return; }
    for (const entry of await readdir(dir,{withFileTypes:true})) {
      if (entry.name.startsWith('.')||['design-workspace','design-studio-assets','design-studio-history'].includes(entry.name)||ignored.has(entry.name)||entry.isSymbolicLink()) continue;
      if (++count>1500) { exhausted=true;return; }
      const path=resolve(dir,entry.name), name=relative(root,path);
      if (entry.isDirectory()) await walk(path,depth+1);
      else if (entry.isFile()) {
        if (['.tsx','.jsx'].includes(extname(name)) && report.components.length<40) report.components.push(name);
        if (extname(name)==='.css' && report.cssFiles.length<80) {
          report.cssFiles.push(name);
          try {
            const sheet=postcss.parse(await readLimited(path)),managed=isManagedStylesheet(sheet);
            sheet.walkDecls(d=>{
              if(d.parent?.type!=='rule'&&!(d.parent?.type==='atrule'&&d.parent.name==='theme'&&d.prop.startsWith('--')))return;
              const parsed=parseProjectColor(d.value),rawSelector=d.parent.type==='rule'?d.parent.selector:':root',duplicate=rawSelector.match(/^:is\((.+)\):is\(\1\)$/),selector=duplicate?.[1]??rawSelector,theme=colorSelector(selector),supported=theme!==undefined&&unconditional(d.parent)&&!d.important;
              if(!d.prop.startsWith('--')){
                if(parsed&&unconditional(d.parent)&&!d.important&&['color','background','background-color','border-color','fill','stroke'].includes(d.prop)&&report.hardcoded!.length<120)report.hardcoded!.push({file:name.replaceAll('\\','/'),selector,property:d.prop,value:d.value});
                return;
              }
              if(!parsed){if(/^(#|rgba?\(|hsla?\(|oklch\(|color\()/i.test(d.value)&&report.detected.length<120)report.detected.push({file:name,variable:d.prop,value:d.value,selector,theme:theme??'other selector',supported:false,priority:1});return;}
              const priority=managed?2:1;
              if(report.detected.length<120)report.detected.push({file:name,variable:d.prop,value:d.value,hex:parsed.hex,format:parsed.format,selector,theme:theme??'other selector',supported,priority});

            });
          } catch (e) { report.notes.push(`${name}: ${(e as Error).message}`); }
        }
      }
    }
  }
  await walk(root,0);
  if (report.cssFiles.length) report.styling.push('CSS'+(report.detected.length?' custom properties':''));
  if (exhausted) report.notes.push('Inspection limited to 1,500 entries and six directory levels.');
  const aliases={text:['--text','--foreground','--color-text','--color-foreground'],background:['--background','--bg','--color-background'],primary:['--primary','--color-primary'],secondary:['--secondary','--color-secondary'],accent:['--accent','--color-accent']};
  const supported=report.detected.filter(d=>d.supported);
  report.config.application.applyTypography=false;report.config.application.applyLayout=false;
  const light=[...new Set(supported.filter(d=>d.theme==='light').map(d=>d.selector!.replace(':root:root',':root')))];if(light.length===1)report.config.application.lightSelector=light[0] as ':root'|'html'|'body';
  report.config.application.formats={};report.config.application.darkFormats={};
  const dark=[...new Set(supported.filter(d=>d.theme==='dark').map(d=>d.selector!.replace(':root:root',':root')))];
  if(dark.length===1)report.config.application.darkSelector=dark[0];
  if(dark.length>1)report.notes.push('Multiple dark selectors found. Choose a single supported theme integration before Apply.');
  for(const role of roles){
    const candidates=[report.config.tokenMappings[role],...aliases[role]].filter(variable=>supported.some(d=>d.variable===variable));
    if(candidates.length===1)report.config.tokenMappings[role]=candidates[0];
    if(candidates.length>1)report.notes.push(`${role}: multiple candidate variables (${candidates.join(', ')}); choose in Map project colors.`);
    for(const theme of ['light','dark'] as const){const found=supported.filter(d=>d.variable===report.config.tokenMappings[role]&&d.theme===theme).sort((a,b)=>a.priority-b.priority).at(-1);if(found){report.config.palettes[theme][role]=found.hex!;report.config.application[theme==='light'?'formats':'darkFormats']![role]=found.format;}}
  }
  for(const token of tokens.filter(token=>!roles.includes(token as typeof roles[number])))for(const theme of ['light','dark'] as const){const found=supported.filter(d=>d.variable===report.config.tokenMappings[token]&&d.theme===theme).sort((a,b)=>a.priority-b.priority).at(-1);if(found){report.config.overrides[theme][token as keyof typeof report.config.overrides.light]=found.hex!;report.config.application[theme==='light'?'formats':'darkFormats']![token]=found.format;}}
  report.notes.push('Opaque HEX (including short HEX), RGB, HSL, OKLCH and numeric HSL/RGB channels are inspected. Root/body tokens, .dark/data-theme dark selectors and unconditional cascade layers are supported. Alpha, expressions, conditional selectors and !important need manual integration. Inferred names require verification against visible consumers. Unmatched roles and typography use defaults.');
  report.notes.push('No code, environment files, or secrets are uploaded. Inspection never executes project code; the automatic React/Vite preview runs the local Vite configuration.');
  return report;
}
